import assert from 'node:assert/strict';

export default async function verifyConsole({page, origin, fixture, evidence}) {
  const responses = [];
  page.on('response', response => {
    if (response.url().includes('/end-call')) responses.push({url:response.url(),status:response.status()});
  });
  await page.goto(origin+'/admin/demo-operations');
  const card = name => page.locator('details').filter({has:page.getByText('Capture consent · synthetic-browser-'+name,{exact:true})}).locator('..');
  const repeat=card('repeat'), stale=card('stale'), stopped=card('stopped');
  await repeat.getByRole('button',{name:'End call',exact:true}).waitFor();
  for(const row of [repeat,stale,stopped]) {
    await row.locator('summary').first().click();
    for(const label of ['Disclosure version/reference','Evidence reference','Jurisdiction basis']) await row.getByLabel(label,{exact:true}).fill('synthetic');
    for(const action of ['grant','refuse']) {
      const button=row.getByRole('button',{name:'Record '+action,exact:true});
      assert.equal(await button.isDisabled(),true);
      assert.equal(await button.evaluate(e=>getComputedStyle(e).opacity),'0.4');
      assert.equal(await button.evaluate(e=>getComputedStyle(e).cursor),'not-allowed');
    }
  }
  assert.equal(await stopped.getByRole('button',{name:'End call',exact:true}).isDisabled(),true);
  assert.match(await stopped.innerText(),/confirmed by authenticated exact-call hangup/);
  assert.equal(await card('expired').getByRole('button',{name:'End call',exact:true}).isDisabled(),true);
  assert.match(await card('expired').innerText(),/not confirmed — expired/);
  const ended=card('ended'), disconnected=card('disconnected');
  assert.equal(await ended.getByRole('button',{name:'End call',exact:true}).isDisabled(),false);
  assert.match(await ended.innerText(),/fresh_exact_active_evidence/);
  assert.match(await ended.innerText(),/Disconnection: not recorded/);
  assert.equal(await disconnected.getByRole('button',{name:'End call',exact:true}).isDisabled(),true);
  assert.match(await disconnected.innerText(),/call_disconnected/);
  assert.match(await disconnected.innerText(),/Disconnection: recorded at .* historical fact does not expire/);
  assert.match(await disconnected.innerText(),/Current raw hangup proof: not confirmed — expired/);
  assert.doesNotMatch(await disconnected.innerText(),/Operator fallback/);
  assert.match(await page.locator('body').innerText(),/Normalized call records — not disconnection proof/);
  const normalized=page.locator('tr').filter({hasText:'synthetic-browser-repeat'});
  assert.match(await normalized.innerText(),/completed/);
  const first=page.waitForResponse(r=>r.url().includes('/end-call'));
  await repeat.getByRole('button',{name:'End call',exact:true}).evaluate(button=>{button.click();button.click();});
  assert.equal((await first).status(),202);
  await page.waitForFunction(()=>Array.from(document.querySelectorAll('[role=status]')).some(e=>e.textContent.includes('Repeated requests do not resend')));
  assert.equal(responses.length,1);
  await page.waitForFunction(()=>Array.from(document.querySelectorAll('button')).filter(e=>e.textContent==='End call'&&!e.disabled).length===2);
  assert.equal(await repeat.getByRole('button',{name:'End call',exact:true}).isDisabled(),true);
  await repeat.getByRole('button',{name:'End call',exact:true}).evaluate(button=>button.click());
  assert.equal(responses.length,1);
  assert.match(await repeat.innerText(),/Operator fallback: do not retry/);
  assert.match(await repeat.innerText(),/Carrier console capabilities have not been verified/);
  const endedResponse=page.waitForResponse(r=>r.url().includes('/end-call'));
  await ended.getByRole('button',{name:'End call',exact:true}).click();
  assert.equal((await endedResponse).status(),202);
  await page.waitForFunction(()=>Array.from(document.querySelectorAll('button')).filter(e=>e.textContent==='End call'&&!e.disabled).length===1);
  assert.equal(responses.length,2);
  await fixture('bump');
  const rejected=page.waitForResponse(r=>r.url().includes('/end-call'));
  await stale.getByRole('button',{name:'End call',exact:true}).click();
  assert.equal((await rejected).status(),409);
  const count=responses.length;
  const refresh=page.waitForResponse(r=>r.request().method()==='GET'&&r.url().includes('/admin/demo-operations'));
  await stopped.getByRole('button',{name:'Refresh disconnection evidence',exact:true}).click();
  await refresh;
  assert.equal(responses.length,count);
  const state=await fixture('inspect');
  assert.equal(state.commands,2);
  assert.equal(state.endedCommands,1);
  assert.equal(state.staleCommands,0);
  assert.equal(state.consentEvents,0);
  assert.equal(state.withdrawn,6);
  assert.equal(state.commandsByType.every(row=>row.command_type==='hangup'),true);
  assert.match(await repeat.innerText(),/Disconnection: not recorded/);
  assert.match(await repeat.innerText(),/Current raw hangup proof: not confirmed/);
  await page.screenshot({path:evidence+'/console.png',fullPage:true});
  await fixture('erase');
  await page.reload();
  assert.match(await stopped.innerText(),/not confirmed — erased/);
  assert.equal(await stopped.getByRole('button',{name:'End call',exact:true}).isDisabled(),true);
  assert.match(await stale.innerText(),/account-level/);
  assert.equal(await stale.getByRole('button',{name:'End call',exact:true}).isDisabled(),true);
  await page.screenshot({path:evidence+'/erased.png',fullPage:true});
  return {responses,state,checks:['terminal consent visibly disabled with filled inputs','STOPPED exact proof disables End call','STOP_PENDING End call','same-turn double click sends once','later click disabled after claim','stale generation rejected 409','refresh GET only','no consent reopening','expired proof blocks dispatch','erased proof blocks account ambiguity','withdrawn conversation end still allows one End call','recorded disconnection with expired proof stays disabled without fallback','normalized completed is not disconnection proof','explicit unverified carrier fallback']};
};

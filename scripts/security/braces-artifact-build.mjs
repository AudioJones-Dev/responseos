import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import crypto from 'node:crypto';
import {spawn} from 'node:child_process';
const root=process.cwd();
const sha=process.env.SECURITY_APPLICATION_SHA||'4e1f353117696658988bca171e4e0e51c0fb1b96';
if(!/^[0-9a-f]{40}$/.test(sha))throw new Error('Application commit must be a full SHA');
const scratch=fs.mkdtempSync(path.join(os.tmpdir(),'responseos-artifact-'));
const checkout=path.join(scratch,'checkout');
fs.mkdirSync(checkout);
const evidence=path.join(root,'.security-evidence','artifact-verification');
fs.mkdirSync(evidence,{recursive:true});
const node=process.execPath;
const npm=process.env.SECURITY_NPM_CLI||process.env.npm_execpath;
if(!npm)throw new Error('Set SECURITY_NPM_CLI to pinned npm 11.16.0 CLI');
const env={};
for(const name of ['SystemRoot','WINDIR','COMSPEC','PATHEXT','TEMP','TMP','USERPROFILE','APPDATA','LOCALAPPDATA','HOME','PATH']) if(process.env[name]) env[name]=process.env[name];
env.PATH=[path.dirname(node),...(process.platform==='win32'?['C:/Program Files/Git/bin']:[]),process.env.PATH||''].join(path.delimiter);
Object.assign(env,{NODE_ENV:'production',NEXT_TELEMETRY_DISABLED:'1',RESPONSEOS_BUILD_SHA:sha,RESPONSEOS_REQUIRE_AUTH:'true',NEXT_PUBLIC_APP_URL:'http://127.0.0.1:3187',npm_config_userconfig:path.join(scratch,'empty.npmrc'),npm_config_include:'dev'});
fs.writeFileSync(env.npm_config_userconfig,'');
const hash=file=>crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex');
const summary={startedAt:new Date().toISOString(),sourceCommit:sha,platform:process.platform,node:process.version,scratch,checkout,evidence,env,steps:[],buildSucceeded:false};
const save=()=>fs.writeFileSync(path.join(evidence,'build-summary.json'),JSON.stringify(summary,null,2)+'\n');
async function step(name,exe,args,cwd=checkout,timeout=900000){
 console.log('Starting '+name);
 const output=fs.createWriteStream(path.join(evidence,name+'.log'));
 const started=Date.now();
 const exit=await new Promise(resolve=>{
  const child=spawn(exe,args,{cwd,env,windowsHide:true,stdio:['ignore','pipe','pipe']});
  let timedOut=false;
  child.stdout.pipe(output,{end:false});child.stderr.pipe(output,{end:false});
  const timer=setTimeout(()=>{timedOut=true;child.kill();},timeout);
  child.on('error',error=>{output.write(String(error));});
  child.on('close',(code,signal)=>{clearTimeout(timer);resolve({code,signal,timedOut});});
 });
 await new Promise(resolve=>output.end(resolve));
 summary.steps.push({name,exe,args,...exit,elapsedMs:Date.now()-started});save();
 console.log(name+': '+JSON.stringify(exit));
 return exit.code===0&&!exit.timedOut;
}
const git=process.platform==='win32'?'C:/Program Files/Git/cmd/git.exe':'git';
if(!await step('export',git,['archive','--format=tar','--output='+path.join(scratch,'source.tar'),sha],root)) process.exit(1);
if(!await step('extract',process.platform==='win32'?path.join(process.env.SystemRoot,'System32/tar.exe'):'tar',['-xf',path.join(scratch,'source.tar'),'-C',checkout],root)) process.exit(1);
summary.sourceHashes=Object.fromEntries(['package.json','package-lock.json','next.config.ts','eslint.config.mjs','proxy.ts','scripts/patch-minimatch-cjs-compat.mjs'].map(file=>[file,hash(path.join(checkout,file))]));save();
if(!await step('install',node,[npm,'ci','--ignore-scripts','--include=dev','--no-fund'])) process.exit(1);
await step('audit',node,[npm,'audit','--json']);
if(!await step('compatibility-postinstall',node,[path.join(checkout,'scripts/patch-minimatch-cjs-compat.mjs')])) process.exit(1);
if(!await step('prisma-generate',node,[path.join(checkout,'node_modules/prisma/build/index.js'),'generate'])) process.exit(1);
if(!await step('build',node,[npm,'run','build'])) process.exit(1);
summary.buildSucceeded=true;
summary.packageFilesUnchanged=['package.json','package-lock.json','next.config.ts','eslint.config.mjs','proxy.ts','scripts/patch-minimatch-cjs-compat.mjs'].every(file=>summary.sourceHashes[file]===hash(path.join(checkout,file)));
summary.finishedAt=new Date().toISOString();save();
console.log('Fresh build succeeded. Evidence: '+evidence);
